def is_relevant(card, accepted: list) -> bool:
    for a in accepted:
        if isinstance(a, str) and card.card_id == a:
            return True
        if isinstance(a, tuple) and a[0] == "DOC" and card.kind == "doc":
            if card.meta.get("doc") == a[1] and a[2] in card.meta.get("heading", ""):
                return True
    return False
